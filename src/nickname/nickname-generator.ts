function pick<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

function rollD10(): number {
  return Math.floor(Math.random() * 10) + 1;
}

function rollD20(): number {
  return Math.floor(Math.random() * 20) + 1;
}

function rollD100(): number {
  return Math.floor(Math.random() * 99) + 1;
}

export function generateNickname(): string {
  const pattern = rollD10();

  switch (pattern) {
    case 1:
      return `${pick(ADJECTIVES)}${pick(ROLES)}`;
    case 2:
      return `${pick(CREATURES)}${rollD100()}`;
    case 3:
      return `${pick(NAMES)}${pick(EPITHETS)}`;
    case 4:
      return `${pick(TITLES)}_${pick(ROLES)}`;
    case 5:
      return `${pick(ADJECTIVES)}_${pick(CREATURES)}`;
    case 6:
      return `${pick(NAMES)}_${rollD100()}`;
    case 7:
      return `${pick(CREATURES)}Из${pick(LOCATIONS)}`;
    case 8:
      return `${pick(NAMES)}${pick(MISFORTUNES)}`;
    case 9:
      return `${pick(ADJECTIVES)}${pick(CREATURES)}_${rollD20()}`;
    case 10:
    default:
      return pick(FUNNY_COMPOUNDS);
  }
}
